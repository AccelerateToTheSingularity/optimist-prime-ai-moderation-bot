"""Tests for bot_comment_format.py."""

import unittest

from bot_comment_format import (
    format_bot_comment,
    format_summary_comment,
    BOT_COMMENT_FOOTER,
    CURRENT_FOOTER_REGEX,
    strip_bot_footer,
)


class TestBotCommentFormat(unittest.TestCase):
    def test_does_not_append_footer_to_plain_text(self):
        result = format_bot_comment("Hello world")
        self.assertEqual(result, "Hello world")
        self.assertNotIn("AI assistant", result)

    def test_idempotent_does_not_duplicate_footer(self):
        first = format_bot_comment("Test comment")
        second = format_bot_comment(first)
        self.assertEqual(first, second)

    def test_replaces_old_footer_format(self):
        old_text = "Some text\n\n---\n**AI assistant - generated by Optimist Prime**"
        result = format_bot_comment(old_text)
        self.assertEqual(result, "Some text")

    def test_handles_empty_body(self):
        result = format_bot_comment("")
        self.assertEqual(result, "")

    def test_handles_body_with_trailing_whitespace(self):
        result = format_bot_comment("Text  \n\n")
        self.assertEqual(result, "Text")

    def test_preserves_a_plain_trailing_separator(self):
        result = format_bot_comment("Text\n\n---")
        self.assertEqual(result, "Text\n\n---")

    def test_footer_regex_matches_standard_footer(self):
        text = f"Some text\n\n---\n{BOT_COMMENT_FOOTER}"
        match = CURRENT_FOOTER_REGEX.search(text)
        self.assertIsNotNone(match)

    def test_footer_regex_matches_bold_footer(self):
        text = f"Some text\n\n---\n**{BOT_COMMENT_FOOTER}**"
        match = CURRENT_FOOTER_REGEX.search(text)
        self.assertIsNotNone(match)

    def test_plain_reply_contains_no_summon_phrase(self):
        result = format_bot_comment("Helpful answer")
        self.assertNotIn("!bot", result)
        self.assertNotIn("mod bot", result.lower())

    def test_legacy_footer_is_replaced(self):
        result = format_bot_comment(
            "Helpful answer\n\n---\n*^(AI assistant · generated by Optimist Prime)*"
        )
        self.assertNotIn("AI assistant", result)
        self.assertNotIn("!bot", result)

    def test_strip_bot_footer_removes_legacy_and_current_footers(self):
        legacy = "Reply\n\n---\n*^(AI assistant · mention the bot, mod bot, or use !bot)*"
        current = f"Reply\n\n---\n{BOT_COMMENT_FOOTER}"
        self.assertEqual(strip_bot_footer(legacy), "Reply")
        self.assertEqual(strip_bot_footer(current), "Reply")

    def test_summary_formatter_does_not_add_a_footer(self):
        summary = "**TLDR:** Useful summary"
        self.assertEqual(format_summary_comment(summary), summary)




    def test_summary_formatter_strips_historical_prompt_footer(self):
        old_footer = "Tip: Example additional note."
        text = f"Summary\n\n---\n*^({old_footer})*"
        self.assertEqual(format_summary_comment(text), "Summary")

    def test_strips_historical_summary_footer_formats(self):
        self.assertEqual(strip_bot_footer("Summary\n\n---\n*^(Ask me a question.)*"), "Summary")
        self.assertEqual(strip_bot_footer("Summary\n\n---\n*^(Tip: Ask me a question.)*"), "Summary")

    def test_ordinary_reply_formatter_does_not_add_summary_footer(self):
        self.assertEqual(format_bot_comment("A personal reply"), "A personal reply")


if __name__ == "__main__":
    unittest.main()
