"""Formatting helpers for Optimist Prime replies and summaries."""

import re

BOT_COMMENT_FOOTER = "*^(AI assistant · generated by Optimist Prime)*"

CURRENT_FOOTER_REGEX = re.compile(
    r"\*{1,3}\^?\(?\s*AI assistant\s*(?:·|-)?\s*generated by Optimist Prime\s*\)?\*{1,3}",
    re.IGNORECASE,
)
SUMMARY_TIP_FOOTER_REGEX = re.compile(r"(?m)^\*\^\((?:Tip:\s*)?.*\)\*\s*$")


def format_bot_comment(body: str) -> str:
    """Return clean public comment text without appending a footer."""
    return strip_bot_footer(str(body or ""))


def format_summary_comment(body: str) -> str:
    """Return summary text without adding an extra footer."""
    return strip_bot_footer(str(body or ""))


def strip_bot_footer(text: str) -> str:
    """Remove current or legacy bot footers before summon detection."""
    original = str(text or "")
    without_footer = SUMMARY_TIP_FOOTER_REGEX.sub("", original)
    without_footer = CURRENT_FOOTER_REGEX.sub("", without_footer)
    if without_footer == original:
        return original.strip()
    without_separator = re.sub(r"\n\s*---\s*$", "", without_footer)
    return without_separator.strip()
